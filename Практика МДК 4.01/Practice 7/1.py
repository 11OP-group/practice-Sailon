rating = int(input("Введите числовой рейтинг продукта: "))

match rating:
    case 10 | 9 | 8:
        print(f"Рейтинг {rating} -> Отличный продукт! 😀 Отличный продукт")
    case 7 | 6 | 5:
        print(f"Рейтинг {rating} -> Средний продукт. 👍 Можно попробовать")
    case 4 | 3 | 2 | 1:
        print(f"Рейтинг {rating} -> Плохой продукт. 😨 Не стоит пробовать")
 